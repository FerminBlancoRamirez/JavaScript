//Switch
let nivel = "pro"

switch(nivel){
    case "basico": console.log("Eres muy basico")
        break
    case "pro" : console.log("Eres un pro")
        break
    case "vip" : console.log("Eres vip")
        break
    default: console.log("Error, el nivel no es valido")
}

//While
let num = 1
while(num <= 5){
    console.log(num)
    num++
}

//DO WHile

let cont=1
do{
    console.log(cont)
    cont++
}while(cont<=5)


//For

for(let i=1; i<=5; i++){
    console.log(i)
}